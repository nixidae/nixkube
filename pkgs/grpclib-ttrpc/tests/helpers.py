class FakeTransport(asyncio.Transport):
    """Stub transport that records written bytes."""

    def __init__(self) -> None:
        super().__init__()
        self.written = bytearray()
        self._closing = False

    def write(self, data: bytes) -> None:  # type: ignore[override]
        self.written.extend(data)

    def is_closing(self) -> bool:
        return self._closing

    def close(self) -> None:
        self._closing = True

    # asyncio.BaseTransport requires this
    def get_extra_info(self, name: str, default: object = None) -> object:
        return default

    def pop_frames(self) -> list[Frame]:
        """Return the frames written so far, and clear the buffer."""
        frames: list[Frame] = []
        data = bytes(self.written)
        self.written.clear()
        while len(data) >= HEADER_SIZE:
            decoded = decode_frame(data)
            frames.append(Frame(decoded.stream_id, decoded.msg_type, decoded.flags, decoded.payload))
            data = decoded.remainder
        return frames


